import test from 'node:test';
import assert from 'node:assert/strict';
import { mkdir } from 'node:fs/promises';
import { harnessFixture } from './fixtures/harness-page.mjs';
import { openUsage, usageArtifacts } from './fixtures/usage-controls.mjs';
import { aggregateUsage, usageRecord } from '../usage-history.mjs';

const machines = [{ id: 'laptop', name: 'Laptop', self: true, reachable: true }, { id: 'pc', name: 'PC', home: true, reachable: true }];
const history = (owner, input) => ({ ...aggregateUsage([usageRecord({ type: 'message', id: `${owner}-response`, timestamp: '2026-10-11T10:00:00Z', message: { role: 'assistant', provider: 'fixture', model: 'rated', usage: { input, output: 0, cacheRead: 0, cacheWrite: 0 } } }, { agent: 'pi', device: owner })], { owner, now: Date.parse('2026-10-11T12:00:00Z'), models: [{ provider: 'fixture', id: 'rated', cost: { input: 1, output: 1, cacheRead: 0, cacheWrite: 0 } }] }), historyCoverage: { complete: true } });
const pcHistory = history('pc', 9000000), laptopHistory = history('laptop', 1000000);
for (const width of [1200, 390]) test(`laptop window reads PC, caches an explicitly stale reflection, switches locally and revalidates (${width}px)`, async t => {
  const f = await harnessFixture({ site: true, machines, viewport: { width, height: 900 }, hasTouch: width < 500, messages: [{ role: 'assistant', content: [{ type: 'text', text: 'Synthetic laptop conversation' }] }] });
  t.after(() => f.close()); const { page } = f;
  const calls = []; let offline = false;
  f.answer = (c, owner) => {
    calls.push({ ...c, owner: owner || 'laptop' });
    if (c.type === 'usage-history') return owner === 'pc' ? offline ? Promise.reject(new Error('PRIVATE ERROR')) : pcHistory : laptopHistory;
    if (c.type === 'usage') return owner === 'pc' ? offline ? Promise.reject(new Error('PRIVATE ERROR')) : [{ agent: 'pi', signedIn: true, accountId: 'pc-account', windows: [{ name: 'PC limit', used: 42, resetsAt: Date.now() + 3600000 }], resetCredits: { availableCount: 1, nextCreditId: 'pc-credit', nextExpiresAt: Date.now() + 86400000 } }] : [{ agent: 'pi', signedIn: false }];
    if (c.type === 'codex-reset-consume') return { outcome: 'reset' };
  };
  await page.evaluate(() => localStorage.setItem('imperfect:usage-page:v1', JSON.stringify({ metric: 'cost', period: 30 })));
  await openUsage(page); const pane = page.locator('.usage-box');
  await pane.locator('.usage-headline').getByText('USD 9.00').waitFor();
  assert.equal(await pane.locator('.usage-owner-scope').innerText(), 'PC · all computers');
  assert.equal(calls.find(c => c.type === 'usage-history').owner, 'pc');
  assert.equal(f.commands.some(c => ['tab-focus', 'session-attach', 'tab-new'].includes(c.type)), false, 'does not select or start a PC conversation');
  await pane.getByRole('button', { name: 'Limits', exact: true }).click(); await pane.getByText('PC limit', { exact: true }).waitFor();
  await pane.getByRole('button', { name: 'Use reset', exact: true }).click();
  assert.match(await pane.getByRole('group', { name: 'Confirm Codex reset' }).innerText(), /pc-credit.*pc-account, computer PC/);
  await pane.getByRole('button', { name: 'Confirm use reset', exact: true }).click(); await pane.getByRole('status').waitFor();
  const reset = calls.find(c => c.type === 'codex-reset-consume'); assert.equal(reset.owner, 'pc'); assert.equal(reset.scope, 'computer');
  offline = true;
  await pane.getByRole('button', { name: 'Refresh limits' }).click();
  await pane.getByText('Updated limits unavailable (computer may be offline) · try Refresh').waitFor();
  assert.match(await pane.locator('.usage-owner-scope').innerText(), /PC · all computers · not live, as of/);
  assert.equal(await pane.getByRole('button', { name: 'Use reset', exact: true }).count(), 0);
  await pane.getByRole('button', { name: 'Cost', exact: true }).click();
  await pane.getByRole('button', { name: 'Refresh usage' }).click(); await pane.getByText('Updated usage unavailable (computer may be offline) · try Refresh').waitFor();
  assert.match(await pane.locator('.usage-headline').innerText(), /USD 9.00/);
  assert.match(await pane.locator('.usage-owner-scope').innerText(), /not live, as of/);
  assert.doesNotMatch(await pane.innerText(), /PRIVATE ERROR/);
  const localCalls = calls.filter(c => c.type === 'usage-history' && c.owner === 'laptop').length;
  assert.equal(localCalls, 0, 'offline PC never silently becomes laptop');
  await pane.getByRole('button', { name: 'Back to conversation' }).click();
  await page.reload(); await page.locator('#entry-output .gui-assistant').first().waitFor();
  await openUsage(page); await pane.getByText('Updated usage unavailable (computer may be offline) · try Refresh').waitFor();
  assert.match(await pane.locator('.usage-headline').innerText(), /USD 9.00/);
  await pane.getByRole('button', { name: 'This computer only', exact: true }).click();
  await pane.locator('.usage-headline').getByText('USD 1.00').waitFor();
  assert.equal(await pane.locator('.usage-owner-scope').innerText(), 'Laptop · this computer only');
  assert.equal(calls.filter(c => c.type === 'usage-history').at(-1).thisComputerOnly, true);
  await pane.getByRole('button', { name: 'All computers', exact: true }).click(); await pane.getByText('Updated usage unavailable (computer may be offline) · try Refresh').waitFor();
  assert.match(await pane.locator('.usage-headline').innerText(), /USD 9.00/);
  assert.ok(await pane.locator('.usage-content').evaluate(n => n.scrollWidth <= n.clientWidth));
  await mkdir(usageArtifacts('usage-authority'), { recursive: true });
  await page.screenshot({ path: `${usageArtifacts('usage-authority')}/offline-${width}.png` });
  offline = false;
  await page.evaluate(() => { const now = Date.now; Date.now = () => now() + 181000; });
  await page.waitForFunction(() => !document.querySelector('.usage-owner-scope').textContent.includes('not live'));
  assert.equal(calls.filter(c => c.type === 'usage-history').at(-1).owner, 'pc');
  await page.screenshot({ path: `${usageArtifacts('usage-authority')}/pc-${width}.png` });
  const beforeHidden = calls.filter(c => c.type === 'usage-history').length;
  await page.evaluate(() => {
    Object.defineProperty(document, 'hidden', { configurable: true, value: true });
    const now = Date.now; Date.now = () => now() + 181000;
  });
  await page.waitForTimeout(600);
  assert.equal(calls.filter(c => c.type === 'usage-history').length, beforeHidden, 'hidden panels do not poll');
  await page.evaluate(() => Object.defineProperty(document, 'hidden', { configurable: true, value: false }));
  await page.waitForTimeout(600);
  assert.ok(calls.filter(c => c.type === 'usage-history').length > beforeHidden, 'visible panels revalidate after a few minutes');
  assert.deepEqual(f.errors, []);
});

test('unreachable PC with no reflection says PC, not live local data; explicit local scope recovers', async t => {
  const f = await harnessFixture({ machines: [machines[0], { ...machines[1], reachable: false }], messages: [{ role: 'assistant', content: [{ type: 'text', text: 'Synthetic fixture' }] }] }); t.after(() => f.close());
  const { page } = f; f.refuse = true;
  f.answer = (c, owner) => c.type === 'usage-history' ? owner === 'pc' ? Promise.reject(new Error('private')) : laptopHistory : undefined;
  await page.evaluate(() => localStorage.setItem('imperfect:usage-page:v1', JSON.stringify({ metric: 'cost', period: 30 })));
  await openUsage(page);
  await page.getByText('Historical usage unavailable (computer may be offline) · try Refresh').waitFor();
  assert.equal(await page.locator('.usage-owner-scope').innerText(), 'PC · all computers');
  assert.equal(await page.locator('.usage-headline').count(), 0);
  await page.getByRole('button', { name: 'This computer only', exact: true }).click();
  await page.locator('.usage-headline').getByText('USD 1.00').waitFor();
  assert.equal(await page.locator('.usage-owner-scope').innerText(), 'Laptop · this computer only');
  assert.deepEqual(f.errors, []);
});
